export function Icon({ name, size = 18, className = '' }) {
  const node = MAP[name];
  if (!node) return null;
  const [, attrs, children] = node;
  return h(
    'svg',
    {
      ...attrs,
      width: size,
      height: size,
      'stroke-width': 1.5,
      class: `icon ${className}`.trim(),
      'aria-hidden': 'true',
      focusable: 'false',
    },
    children.map(([tag, a], i) => h(tag, { key: i, ...a })),
  );
}
export const hasIcon = (name) => Object.hasOwn(MAP, name);
